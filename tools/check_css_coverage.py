"""Fail when a client uses a style class its CSS bundle does not define, or when
the generated admin CSS is out of date.

Two clients, two vendored bundles:

* the main app   - ``static/index.html`` against ``static/tailwind.css``;
* the admin app  - ``admin_service/static/{index.html,app.js,docs.html,docs.js}``
                   against ``admin_service/static/tailwind.css`` (+ ``tokens.css``
                   and the component rules in ``styles.css``).

The admin bundles are generated by ``tools/gen_admin_tailwind.py``. This check
also rebuilds them into a temporary directory and diffs the result against the
committed files, so a source change that was not followed by a regeneration fails
here instead of shipping an unstyled element.

Run directly (exit code 1 on drift) or through the unit test that wraps
``run_checks``:

    python tools/check_css_coverage.py
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from css_class_harvest import MARKER_CLASSES, css_escape, harvest_class_tokens

ROOT = Path(__file__).resolve().parents[1]
ADMIN_STATIC = ROOT / "admin_service" / "static"
MAIN_STATIC = ROOT / "static"
GENERATOR = Path(__file__).resolve().parent / "gen_admin_tailwind.py"

# The main app styles these elements through the utility classes that sit beside
# the hook in the same ``class`` attribute; the hook name itself is only a
# ``querySelector`` handle and is deliberately unstyled.
MAIN_JS_HOOKS = {
    "cancel-btn",
    "delete-entry-btn",
    "download-inline-btn",
    "edit-entry-btn",
    "file-icon",
    "file-status-text",
    "job-item",
    "remove-btn",
}

# Same idea for the admin app: the role dropdown carries the `input` styling and
# `role-select` is only the handle the script uses to read/collect its value.
ADMIN_JS_HOOKS = {"role-select"}

_STYLE_BLOCK_RE = re.compile(r"<style[^>]*>(.*?)</style>", re.S)


def _selector_present(token: str, css: str) -> bool:
    """True when ``css`` has a rule whose selector starts with this class."""
    return re.search(re.escape("." + css_escape(token)) + r"(?=\s*[,{+>~:\s])", css) is not None


def _inline_styles(html: str) -> str:
    return "\n".join(_STYLE_BLOCK_RE.findall(html))


class Client:
    def __init__(self, name, sources, style_files, ignores=()):
        self.name = name
        self.sources = [Path(p) for p in sources]
        self.style_files = [Path(p) for p in style_files]
        self.ignores = set(ignores)


CLIENTS = [
    Client(
        "main app",
        sources=[MAIN_STATIC / "index.html"],
        style_files=[MAIN_STATIC / "tailwind.css", MAIN_STATIC / "fonts.css"],
        ignores=MAIN_JS_HOOKS,
    ),
    Client(
        "admin app",
        sources=[
            ADMIN_STATIC / "index.html",
            ADMIN_STATIC / "app.js",
            ADMIN_STATIC / "docs.html",
            ADMIN_STATIC / "docs.js",
        ],
        style_files=[
            ADMIN_STATIC / "tailwind.css",
            ADMIN_STATIC / "tokens.css",
            ADMIN_STATIC / "styles.css",
        ],
        ignores=ADMIN_JS_HOOKS,
    ),
]


def check_client(client: Client) -> list[str]:
    """Return the class tokens ``client`` uses that no stylesheet defines."""
    css_parts = [p.read_text(encoding="utf-8") for p in client.style_files if p.exists()]
    used: set[str] = set()
    for path in client.sources:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        used |= harvest_class_tokens(text)
        if path.suffix == ".html":
            css_parts.append(_inline_styles(text))
    css = "\n".join(css_parts)
    return sorted(
        t
        for t in used
        if t not in MARKER_CLASSES and t not in client.ignores and not _selector_present(t, css)
    )


def check_generated_current() -> list[str]:
    """Rebuild the admin CSS into a temp dir and report files that differ."""
    problems: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [sys.executable, str(GENERATOR), tmp],
            check=True,
            cwd=str(ROOT),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
        )
        for name in ("tailwind.css", "tokens.css"):
            committed = ADMIN_STATIC / name
            fresh = Path(tmp) / name
            if not committed.exists() or committed.read_text(encoding="utf-8") != fresh.read_text(encoding="utf-8"):
                problems.append(
                    f"admin {name} is stale - re-run python tools/gen_admin_tailwind.py"
                )
    return problems


def run_checks() -> list[str]:
    problems: list[str] = []
    for client in CLIENTS:
        missing = check_client(client)
        if missing:
            problems.append(
                f"{client.name}: {len(missing)} class token(s) used but not defined by its CSS: "
                + ", ".join(missing)
            )
    problems.extend(check_generated_current())
    return problems


def main() -> int:
    problems = run_checks()
    if problems:
        print("CSS coverage check FAILED:")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print("CSS coverage check passed: every used class is defined and the generated admin CSS is current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
